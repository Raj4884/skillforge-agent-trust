"""Measure the scanner against the hand-written fixture corpus.

    python tests/corpus_report.py          # print the report
    python tests/corpus_report.py --write  # regenerate docs/EVALUATION.md

Each case in tests/corpus/manifest.json records two things:

* ``should``: the rules a careful reviewer would want to fire on that skill.
* ``expected``: the rules the scanner fires today.

Where they differ, the case is a documented known gap (a miss) or a known
false positive. tests/test_corpus.py fails when the scanner's behavior changes,
so an improvement or a regression always shows up as an explicit diff here.
"""

import json
import sys
from pathlib import Path

from skillforge.engine import scan_skill
from skillforge.scanner import RULES

CORPUS = Path(__file__).resolve().parent / "corpus"
DOC = Path(__file__).resolve().parent.parent / "docs" / "EVALUATION.md"


def load_manifest() -> list[dict]:
    return json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))


def fired_rules(case: str) -> set[str]:
    report = scan_skill(CORPUS / "cases" / case)
    if report.errors:
        raise AssertionError(f"{case}: scan errors: {report.errors}")
    return {finding.rule_id for finding in report.findings}


def _ratio(numerator: int, denominator: int) -> str:
    return "n/a" if denominator == 0 else f"{numerator / denominator:.0%}"


def render_markdown() -> str:
    manifest = load_manifest()
    fired = {row["case"]: fired_rules(row["case"]) for row in manifest}

    malicious = [row for row in manifest if row["label"] == "malicious"]
    benign = [row for row in manifest if row["label"] == "benign"]
    caught = [row for row in malicious if set(row["should"]) <= fired[row["case"]]]
    clean = [row for row in benign if not fired[row["case"]]]

    lines = [
        "# Evaluation on the fixture corpus",
        "",
        "<!-- Generated by `python tests/corpus_report.py --write`. Do not edit by hand. -->",
        "",
        (
            f"The corpus in `tests/corpus/` has {len(manifest)} hand-written skills "
            f"({len(malicious)} that should be flagged, {len(benign)} that should not). "
            "It is small and written by the rule author, so these numbers describe this corpus only. "
            "They are not an estimate of real-world accuracy, and they say nothing about "
            "obfuscated or novel attacks."
        ),
        "",
        "## Summary",
        "",
        f"- Skills that should be flagged and were: **{len(caught)} of {len(malicious)}**",
        f"- Benign skills with no finding: **{len(clean)} of {len(benign)}**",
        "",
        "## Per rule",
        "",
        (
            "A true positive is a rule that fired where a reviewer wanted it. A false negative is a rule that "
            "should have fired and did not. A false positive is a rule that fired where it should not have."
        ),
        "",
        "| Rule | Title | True positives | False negatives | False positives | Recall | Precision |",
        "|---|---|---|---|---|---|---|",
    ]
    for rule_id, title, *_ in RULES:
        tp = sum(1 for row in manifest if rule_id in row["should"] and rule_id in fired[row["case"]])
        fn = sum(1 for row in manifest if rule_id in row["should"] and rule_id not in fired[row["case"]])
        fp = sum(1 for row in manifest if rule_id not in row["should"] and rule_id in fired[row["case"]])
        lines.append(
            f"| {rule_id} | {title} | {tp} | {fn} | {fp} | {_ratio(tp, tp + fn)} | {_ratio(tp, tp + fp)} |"
        )

    gaps = [row for row in malicious if not set(row["should"]) <= fired[row["case"]]]
    false_positives = [row for row in benign if fired[row["case"]]]
    lines += ["", "## Known gaps (should be flagged, are not)", ""]
    lines += [f"- `{row['case']}`: {row['note']}" for row in gaps] or ["- None."]
    lines += ["", "## Known false positives (benign, but flagged)", ""]
    lines += [f"- `{row['case']}`: {row['note']}" for row in false_positives] or ["- None."]
    lines += [
        "",
        "## Adding a case",
        "",
        "1. Create `tests/corpus/cases/<name>/SKILL.md` (and any other files).",
        (
            "2. Add a row to `tests/corpus/manifest.json` with `should` (what a reviewer wants) and "
            "`expected` (what the scanner fires today)."
        ),
        "3. Run `python tests/corpus_report.py --write` and commit the updated page.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render_markdown()
    if "--write" in sys.argv[1:]:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC}")
    else:
        print(text)
